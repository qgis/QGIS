#include "qgswaylandpointerlocker.h"

#include <QGuiApplication>
#include <QWaylandClientExtensionTemplate>
#include <QWindow>

#include "moc_qgswaylandpointerlocker.cpp"

// includes below are autogenerated by qt_generate_wayland_protocol_client_sources from the Wayland xml protocol definitions
#include "qwayland-pointer-constraints-unstable-v1.h"
#include "qwayland-relative-pointer-unstable-v1.h"

class WaylandPointerConstraints : public QWaylandClientExtensionTemplate<WaylandPointerConstraints>, public QtWayland::zwp_pointer_constraints_v1
{
  public:
    WaylandPointerConstraints()
      : QWaylandClientExtensionTemplate( 1 )
    {}
};

class WaylandRelativePointerManager : public QWaylandClientExtensionTemplate<WaylandRelativePointerManager>, public QtWayland::zwp_relative_pointer_manager_v1
{
  public:
    WaylandRelativePointerManager()
      : QWaylandClientExtensionTemplate( 1 )
    {}
};

class WaylandRelativePointer : public QtWayland::zwp_relative_pointer_v1
{
  public:
    WaylandRelativePointer( struct ::zwp_relative_pointer_v1 *obj, QgsWaylandPointerLocker *locker )
      : QtWayland::zwp_relative_pointer_v1( obj )
      , mLocker( locker )
    {}

    void zwp_relative_pointer_v1_relative_motion( uint32_t utime_hi, uint32_t utime_lo, wl_fixed_t dx, wl_fixed_t dy, wl_fixed_t dx_unaccel, wl_fixed_t dy_unaccel ) override
    {
      ( void ) utime_hi;
      ( void ) utime_lo;
      ( void ) dx_unaccel;
      ( void ) dy_unaccel;

      mLocker->handleRelativeMotion( wl_fixed_to_double( dx ), wl_fixed_to_double( dy ) );
    }

    QgsWaylandPointerLocker *mLocker = nullptr;
};

//
// QgsWaylandPointerLocker
//

QgsWaylandPointerLocker::QgsWaylandPointerLocker( QWindow *window, QObject *parent )
  : QgsPointerLocker( window, parent )
  , mConstraints( new WaylandPointerConstraints() )
  , mRelativePointerManager( new WaylandRelativePointerManager() )
{}

QgsWaylandPointerLocker::~QgsWaylandPointerLocker()
{
  if ( mIsLocked )
  {
    unlock();
  }

  delete mConstraints;
  delete mRelativePointerManager;
}

bool QgsWaylandPointerLocker::lock()
{
  if ( mIsLocked || !mWindow || !mConstraints->isInitialized() || !mRelativePointerManager->isInitialized() )
    return false;

  QNativeInterface::QWaylandApplication *waylandApp = qApp->nativeInterface<QNativeInterface::QWaylandApplication>();

  if ( !waylandApp )
  {
    qDebug() << "Could not retrieve wayland app";
    return false;
  }

  struct ::wl_pointer *pointer = waylandApp->pointer();
  if ( !pointer )
  {
    qDebug() << "Could not retrieve wayland pointer from app";
    return false;
  }

  QWindow *targetWindow = mWindow;
  while ( targetWindow && targetWindow->parent() )
  {
    targetWindow = targetWindow->parent();
  }

  if ( !targetWindow )
  {
    qDebug() << "Could not find target";
    return false;
  }

  if ( !targetWindow->handle() )
  {
    qDebug() << "No target window handle, creating";
    targetWindow->create();
  }

  struct ::wl_surface *surface = reinterpret_cast<struct ::wl_surface *>( targetWindow->winId() );
  if ( !surface )
  {
    qDebug() << "Could not retrieve wayland surface";
    return false;
  }

  mLockedPointer = mConstraints->lock_pointer( surface, pointer, nullptr, WaylandPointerConstraints::lifetime_persistent );
  if ( !mLockedPointer )
  {
    qDebug() << "Could not retrieve zwp_locked_pointer_v1";
    return false;
  }

  struct ::zwp_relative_pointer_v1 *relPtr = mRelativePointerManager->get_relative_pointer( pointer );
  if ( !relPtr )
  {
    qDebug() << "Could not retrieve zwp_relative_pointer_v1";
    zwp_locked_pointer_v1_destroy( mLockedPointer );
    mLockedPointer = nullptr;
    return false;
  }

  mRelativePointer = new WaylandRelativePointer( relPtr, this );
  mIsLocked = true;
  return true;
}

bool QgsWaylandPointerLocker::unlock()
{
  if ( !mIsLocked )
    return false;

  if ( mRelativePointer )
  {
    mRelativePointer->destroy();
    delete mRelativePointer;
    mRelativePointer = nullptr;
  }

  if ( mLockedPointer )
  {
    zwp_locked_pointer_v1_destroy( mLockedPointer );
    mLockedPointer = nullptr;
  }

  mIsLocked = false;
  return true;
}

void QgsWaylandPointerLocker::handleRelativeMotion( double dx, double dy )
{
  emit pointerMoved( dx, dy );
}
